func createIdentityTable(t *testing.T, f *sessionExecutionFixture, dependencies []txn.ReadDependency, sql string) (session.TableCommandResult, error) {
	t.Helper()
	parsed, err := zpgparse.Parse(sql)
	if err != nil {
		t.Fatal(err)
	}
	binding := f.planning(sql).Bind
	expressionLimits := binding.Limits
	expressionLimits.SourceBytes = 1 << 20
	evaluation := expr.DefaultLimits()
	evaluation.MaxBytes = 128 << 10
	options := session.TableCommandOptions{Binding: bind.CreateDeclarationOptions{Bind: binding, Descriptors: model.DescriptorLimits{MaxBytes: 1 << 20, MaxItems: 1024, MaxDepth: 64}, Owner: (model.Principal{}).OID(), Physical: model.PhysicalIdentity{Generation: 1, EncodingVersion: 1}}, Dependencies: dependencies, Columns: session.ColumnExpressionOptions{Binding: expressionLimits, Evaluation: evaluation, InputBytes: 1 << 20, ResultBytes: 1 << 20}, Indexes: session.IndexExpressionOptions{Binding: expressionLimits, Evaluation: evaluation, InputBytes: 1 << 20, ResultBytes: 1 << 20}, Limits: schema.IndexLimits{MetadataBytes: 128 << 10, EntryBytes: 1 << 20, MaxColumns: 64}, PolicyBytes: 1 << 20}
	return session.ExecuteCreateTable(t.Context(), f.session, parsed.Stmts[0].Stmt.GetCreateStmt(), options)
}
func requireIdentityRows(t *testing.T, f *sessionExecutionFixture, facade *session.SequenceSession, dependencies []txn.ReadDependency, table session.TableCommandResult, sql string, want [][]int64) {
	t.Helper()
	got, err := runDeclarationQuery(t, f, facade, dependencies, sql, table.Mutations)
	if err != nil || !reflect.DeepEqual(got, want) {
		t.Fatalf("%s: got %v,%v; want %v", sql, got, err, want)
	}
}

func TestIdentityAlwaysDefaultsOverridesAndMutationActions(t *testing.T) {
	f, _, _, facade, dependencies := sequenceDDLFixture(t)
	table, err := createIdentityTable(t, f, dependencies, `CREATE TABLE ids(id bigint GENERATED ALWAYS AS IDENTITY(START WITH 10) PRIMARY KEY, value bigint UNIQUE)`)
	if err != nil {
		t.Fatal(err)
	}
	for _, step := range []struct {
		sql  string
		want [][]int64
	}{
		{`INSERT INTO ids(value) VALUES(7) RETURNING id,value`, [][]int64{{10, 7}}},
		{`INSERT INTO ids(id,value) OVERRIDING SYSTEM VALUE VALUES(99,8) RETURNING id,value`, [][]int64{{99, 8}}},
		{`INSERT INTO ids(id,value) OVERRIDING USER VALUE VALUES(123,9) RETURNING id,value`, [][]int64{{11, 9}}},
		{`UPDATE ids SET id=DEFAULT WHERE value=7 RETURNING id,value`, [][]int64{{12, 7}}},
		{`INSERT INTO ids(value) VALUES(8) ON CONFLICT(value) DO UPDATE SET id=DEFAULT RETURNING id,value`, [][]int64{{14, 8}}},
		{`MERGE INTO ids t USING (VALUES(7)) s(v) ON t.value=s.v WHEN MATCHED THEN UPDATE SET id=DEFAULT RETURNING t.id,t.value`, [][]int64{{15, 7}}},
		{`MERGE INTO ids t USING (VALUES(42)) s(v) ON t.value=s.v WHEN NOT MATCHED THEN INSERT(id,value) OVERRIDING USER VALUE VALUES(500,s.v) RETURNING t.id,t.value`, [][]int64{{16, 42}}},
	} {
		requireIdentityRows(t, f, facade, dependencies, table, step.sql, step.want)
	}
	_, err = runDeclarationQuery(t, f, facade, dependencies, `INSERT INTO ids VALUES(999,0)`, table.Mutations)
	requireUniqueSQLState(t, err, "428C9")
	requireSequenceDDLRows(t, f, facade, dependencies, `SELECT currval('ids_id_seq')`, [][]int64{{16}})
}

func TestIdentityByDefaultMixedValuesAndSerialRemainDistinct(t *testing.T) {
	f, _, _, facade, dependencies := sequenceDDLFixture(t)
	identity, err := createIdentityTable(t, f, dependencies, `CREATE TABLE by_ids(id integer GENERATED BY DEFAULT AS IDENTITY(START WITH 5) PRIMARY KEY, value integer)`)
	if err != nil {
		t.Fatal(err)
	}
	requireIdentityRows(t, f, facade, dependencies, identity, `INSERT INTO by_ids VALUES(DEFAULT,1),(20,2),(DEFAULT,3) RETURNING id,value`, [][]int64{{5, 1}, {20, 2}, {6, 3}})
	requireIdentityRows(t, f, facade, dependencies, identity, `UPDATE by_ids SET id=21 WHERE id=20 RETURNING id`, [][]int64{{21}})
	requireIdentityRows(t, f, facade, dependencies, identity, `INSERT INTO by_ids OVERRIDING USER VALUE VALUES(50,4) RETURNING id`, [][]int64{{7}})
	_, err = runDeclarationQuery(t, f, facade, dependencies, `INSERT INTO by_ids VALUES(NULL,5)`, identity.Mutations)
	requireUniqueSQLState(t, err, "23502")
	requireSequenceDDLRows(t, f, facade, dependencies, `SELECT currval('by_ids_id_seq')`, [][]int64{{7}})
	serial, err := createIdentityTable(t, f, dependencies, `CREATE TABLE serial_ids(id serial PRIMARY KEY, value integer)`)
	if err != nil {
		t.Fatal(err)
	}
	requireIdentityRows(t, f, facade, dependencies, serial, `INSERT INTO serial_ids VALUES(40,1) RETURNING id`, [][]int64{{40}})
	requireIdentityRows(t, f, facade, dependencies, serial, `INSERT INTO serial_ids(value) VALUES(2) RETURNING id`, [][]int64{{1}})
	requireIdentityRows(t, f, facade, dependencies, serial, `INSERT INTO serial_ids OVERRIDING USER VALUE VALUES(50,3) RETURNING id`, [][]int64{{50}})
	requireSequenceDDLRows(t, f, facade, dependencies, `SELECT currval('serial_ids_id_seq')`, [][]int64{{1}})
	if _, err := executeSequenceDDL(t, f, dependencies, `ALTER SEQUENCE serial_ids_id_seq OWNED BY NONE`); err != nil {
		t.Fatal(err)
	}
	requireIdentityRows(t, f, facade, dependencies, serial, `INSERT INTO serial_ids(value) VALUES(4) RETURNING id`, [][]int64{{2}})
}

func TestOverriddenIdentityPreservesMultirowAndSelectEffects(t *testing.T) {
	f, _, _, facade, dependencies := sequenceDDLFixture(t)
	if _, err := executeSequenceDDL(t, f, dependencies, `CREATE SEQUENCE input_seq START WITH 100`); err != nil {
		t.Fatal(err)
	}
	table, err := createIdentityTable(t, f, dependencies, `CREATE TABLE ids(id bigint GENERATED ALWAYS AS IDENTITY(START WITH 10), value bigint)`)
	if err != nil {
		t.Fatal(err)
	}
	requireIdentityRows(t, f, facade, dependencies, table, `INSERT INTO ids OVERRIDING USER VALUE VALUES(nextval('input_seq'),1) RETURNING id`, [][]int64{{10}})
	_, err = runSequenceDDLQuery(t, f, facade, dependencies, `SELECT currval('input_seq')`)
	requireUniqueSQLState(t, err, "55000")
	requireIdentityRows(t, f, facade, dependencies, table, `INSERT INTO ids OVERRIDING USER VALUE VALUES(nextval('input_seq'),2),(nextval('input_seq'),3) RETURNING id`, [][]int64{{11}, {12}})
	requireSequenceDDLRows(t, f, facade, dependencies, `SELECT currval('input_seq')`, [][]int64{{101}})
	requireIdentityRows(t, f, facade, dependencies, table, `INSERT INTO ids OVERRIDING USER VALUE SELECT nextval('input_seq'),4 RETURNING id`, [][]int64{{13}})
	requireSequenceDDLRows(t, f, facade, dependencies, `SELECT currval('input_seq')`, [][]int64{{102}})
}

func TestIdentityOwnershipCannotBeDetached(t *testing.T) {
	f, _, _, facade, dependencies := sequenceDDLFixture(t)
	table, err := createIdentityTable(t, f, dependencies, `CREATE TABLE ids(id bigint GENERATED ALWAYS AS IDENTITY(CACHE 3))`)
	if err != nil {
		t.Fatal(err)
	}
	requireIdentityRows(t, f, facade, dependencies, table, `INSERT INTO ids DEFAULT VALUES RETURNING id`, [][]int64{{1}})
	_, err = executeSequenceDDL(t, f, dependencies, `ALTER SEQUENCE ids_id_seq OWNED BY NONE`)
	requireUniqueSQLState(t, err, "0A000")
	requireIdentityRows(t, f, facade, dependencies, table, `INSERT INTO ids DEFAULT VALUES RETURNING id`, [][]int64{{4}})
}

func TestOwnedSequenceTableRollbackReclaimsEveryIncarnation(t *testing.T) {
	if testing.Short() {
		t.Skip("long end-to-end fixture; run without -short")
	}
	f, _, _, _, dependencies := sequenceDDLFixture(t)
	if err := f.session.Begin(t.Context(), session.TransactionStart{}); err != nil {
		t.Fatal(err)
	}
	if err := f.session.Savepoint(t.Context(), "before_table"); err != nil {
		t.Fatal(err)
	}
	for range 6 {
		if _, err := createIdentityTable(t, f, dependencies, `CREATE TABLE many_ids(a serial,b bigint GENERATED ALWAYS AS IDENTITY)`); err != nil {
			t.Fatal(err)
		}
		if err := f.session.RollbackTo(t.Context(), "before_table"); err != nil {
			t.Fatal(err)
		}
	}
	if err := f.session.Rollback(t.Context(), false); err != nil {
		t.Fatal(err)
	}
}

func TestIdentityWriteErrorsFollowAnalysisBeforeArbiterPlanning(t *testing.T) {
	f, _, _, facade, dependencies := sequenceDDLFixture(t)
	table, err := createIdentityTable(t, f, dependencies, `CREATE TABLE ids(id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,value bigint UNIQUE)`)
	if err != nil {
		t.Fatal(err)
	}
	for _, scenario := range []struct{ sql, state string }{
		{`INSERT INTO ids VALUES(1000,1000) RETURNING missing_column`, "42703"},
		{`INSERT INTO ids VALUES(1000,1000) ON CONFLICT(missing_column) DO NOTHING`, "42703"},
		{`INSERT INTO ids VALUES(1000,1000) ON CONFLICT((id+1)) DO NOTHING`, "428C9"},
		{`INSERT INTO ids VALUES(1000,1000) ON CONFLICT(value) DO UPDATE SET missing_column=1`, "42703"},
		{`UPDATE ids SET id=1000 RETURNING missing_column`, "42703"},
		{`MERGE INTO ids t USING (VALUES(1)) s(v) ON t.value=s.v WHEN MATCHED THEN UPDATE SET id=1000 RETURNING missing_column`, "42703"},
	} {
		_, err := runDeclarationQuery(t, f, facade, dependencies, scenario.sql, table.Mutations)
		requireUniqueSQLState(t, err, scenario.state)
	}
}
