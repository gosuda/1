package main

import (
	"bytes"
	"crypto/sha256"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
)

var errInvalidData = errors.New("invalid PostgreSQL Unicode data")

// REL_18_4; archive identity and license are in testdata/postgres184.
var sourceFiles = [...]struct {
	name   string
	sha256 string
}{
	{"unicode_norm_table.h", "610b3c71ba92f8aecd36eec71910fac94e0f286abeb80e188f64c1adb031af6f"},
	{"unicode_normprops_table.h", "013280631d4da41d8cd9b4a2b3e3201f6ee25a3f217a4f649332e996fc8b5e84"},
	{"unicode_category_table.h", "fcdd8d788621326ecf91f3167de2e053da8280817509ad7497aa2ef17c430866"},
	{"unicode_version.h", "4edd4c3f9ca47e45e22f0e93980a97ef74ee6c44c32e70443c5c107a1c66602e"},
}

func main() {
	input := flag.String("input", "", "directory containing pinned PostgreSQL Unicode headers")
	output := flag.String("output", "", "generated Go source")
	flag.Parse()
	if err := generate(*input, *output); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(input, output string) error {
	if input == "" || output == "" {
		return fmt.Errorf("%w: input and output paths are required", errInvalidData)
	}
	sources, err := readSources(input)
	if err != nil {
		return err
	}
	data, err := parseData(sources)
	if err != nil {
		return err
	}
	generated, err := render(data)
	if err != nil {
		return err
	}
	if err := os.WriteFile(output, generated, 0644); err != nil {
		return fmt.Errorf("write Unicode tables: %w", err)
	}
	return nil
}

func readSources(input string) (map[string]string, error) {
	sources := make(map[string]string, len(sourceFiles))
	for _, source := range sourceFiles {
		contents, err := os.ReadFile(filepath.Join(input, source.name))
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", source.name, err)
		}
		if actual := fmt.Sprintf("%x", sha256.Sum256(contents)); actual != source.sha256 {
			return nil, fmt.Errorf("%w: %s SHA-256 = %s, want %s", errInvalidData, source.name, actual, source.sha256)
		}
		sources[source.name] = string(contents)
	}
	return sources, nil
}

func render(data *unicodeData) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString("// Code generated by internal/genunicode from PostgreSQL REL_18_4; DO NOT EDIT.\n")
	out.WriteString("// Source: https://www.unicode.org/license.txt, vendored by PostgreSQL REL_18_4 under src/common/unicode (testdata/postgres184/unicode)\n")
	out.WriteString("// License: Unicode-3.0 (see testdata/postgres184/unicode/LICENSE)\n")
	for _, source := range sourceFiles {
		fmt.Fprintf(&out, "// %s SHA-256: %s\n", source.name, source.sha256)
	}
	out.WriteString("\npackage builtin\n\n")
	fmt.Fprintf(&out, "const unicodeDataVersion = %q\n", data.version)
	fmt.Fprintf(&out, "const unicodeMaxDecomposition = %d\n\n", data.maxDecomposition)
	fmt.Fprintf(&out, "// %d normalization entries, %d decomposition codepoints, %d composition pairs.\n", len(data.norm), len(data.decompositions), len(data.compositions))
	out.WriteString("var unicodeNormCodes = [...]rune{\n")
	for _, entry := range data.norm {
		fmt.Fprintf(&out, "0x%x,\n", entry.code)
	}
	out.WriteString("}\n\nvar unicodeNormEntries = [...]unicodeNormEntry{\n")
	for _, entry := range data.norm {
		fmt.Fprintf(&out, "{decompositionIndex: %d, combiningClass: %d, decompositionFlags: 0x%x},\n", entry.index, entry.class, entry.flags)
	}
	out.WriteString("}\n\nvar unicodeDecompositionCodes = [...]rune{\n")
	for _, code := range data.decompositions {
		fmt.Fprintf(&out, "0x%x,\n", code)
	}
	out.WriteString("}\n\nvar unicodeCompositionKeys = [...]uint64{\n")
	for _, pair := range data.compositions {
		fmt.Fprintf(&out, "0x%x,\n", pair.key)
	}
	out.WriteString("}\n\nvar unicodeCompositionCodes = [...]rune{\n")
	for _, pair := range data.compositions {
		fmt.Fprintf(&out, "0x%x,\n", pair.code)
	}
	fmt.Fprintf(&out, "}\n\n// NFC: %d exceptions; NFKC: %d exceptions.\n", len(data.quickChecks[0]), len(data.quickChecks[1]))
	out.WriteString("var unicodeQuickCheckRanges = [...]unicodeQCRange{\n")
	for _, entry := range combineQuickChecks(data.quickChecks) {
		fmt.Fprintf(&out, "{first: 0x%x, last: 0x%x, flags: 0x%x},\n", entry.first, entry.last, entry.flags)
	}
	fmt.Fprintf(&out, "}\n\n// Adjacent assigned categories merged from %d source ranges.\n", len(data.categories))
	out.WriteString("var unicodeAssignedRanges = [...][2]rune{\n")
	for _, entry := range assignedRanges(data.categories) {
		fmt.Fprintf(&out, "{0x%x, 0x%x},\n", entry.first, entry.last)
	}
	out.WriteString("}\n")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format Unicode tables: %w", err)
	}
	return formatted, nil
}
