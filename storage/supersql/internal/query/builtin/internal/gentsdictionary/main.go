package main

import (
	"bytes"
	"crypto/sha256"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
)

var errInvalidData = errors.New("invalid PostgreSQL text search dictionary data")

// tsearchDataFiles are the REL_18_4 dictionary fixtures that PostgreSQL
// installs into $SHAREDIR/tsearch_data. Their digests are pinned here so the
// generated table can never silently drift from the vendored corpus.
var tsearchDataFiles = [...]struct {
	name   string
	sha256 string
}{
	{"ispell_sample.affix", "3a5a3e7a54acd42c27d3c231526ccf8ccf7f29f688ef6ad74dbd04af11309d8f"},
	{"ispell_sample.dict", "e913216b14f04ebfe390f8f6048c408aebab7fe7ff313d61a0d2355146d83397"},
	{"hunspell_sample.affix", "0f1fb5943562c9523d010780b61784c147b49e57596b2497d1396d31c5214aaf"},
	{"hunspell_sample_long.affix", "2132c84f2453d7c3d8bc6b5598a57afe4f9c4aca04d886f46308a070a86df217"},
	{"hunspell_sample_long.dict", "1926afe91b724eb2a3bcd6dd3a03ae3d46691d3246a597d2682a209eb3ada459"},
	{"hunspell_sample_num.affix", "5c2eeed5197453472cc4f918d556a8d092b3b8891579dc8cc0b3db939da52364"},
	{"hunspell_sample_num.dict", "dc6e8fcfaf5bc2b93cd58e8273cae625107ba02dace80061bb6c765ec97dea6f"},
	{"synonym_sample.syn", "59a46c3c25c2b5a1fe174de62bf2f53ce46021e3831eec0eb62d9301ea327e49"},
	{"thesaurus_sample.ths", "346954eaf1def3007ad848731b3c26c203ed12923911b6a0ac198604831f7dc4"},
}

const maxFileBytes = 1 << 20

func main() {
	input := flag.String("input", "", "directory containing pinned PostgreSQL tsearch_data files")
	output := flag.String("output", "", "generated Go source")
	flag.Parse()
	if err := generate(*input, *output); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(input, output string) error {
	if input == "" || output == "" {
		return fmt.Errorf("%w: input and output paths are required", errInvalidData)
	}
	if err := os.MkdirAll(filepath.Dir(output), 0o755); err != nil {
		return fmt.Errorf("create output directory: %w", err)
	}
	var generated bytes.Buffer
	generated.WriteString("// Code generated by internal/gentsdictionary from PostgreSQL REL_18_4; DO NOT EDIT.\n")
	generated.WriteString("// Source: PostgreSQL REL_18_4 src/backend/tsearch/dicts, pinned in testdata/postgres184/tsearch_data.\n")
	generated.WriteString("// License: PostgreSQL (see testdata/postgres184/COPYRIGHT)\n")
	generated.WriteString("// Keys are PostgreSQL tsearch_data filenames (<basename>.<extension>).\n")
	generated.WriteString("package builtin\n\n")
	generated.WriteString("// nativeTextSearchData maps PostgreSQL tsearch_data filenames to their\n// pinned file contents.\nvar nativeTextSearchData = map[string][]byte{\n")
	for _, source := range tsearchDataFiles {
		data, err := os.ReadFile(filepath.Join(input, source.name))
		if err != nil {
			return fmt.Errorf("read %s: %w", source.name, err)
		}
		if len(data) > maxFileBytes {
			return fmt.Errorf("%w: %s exceeds %d bytes", errInvalidData, source.name, maxFileBytes)
		}
		if digest := fmt.Sprintf("%x", sha256.Sum256(data)); digest != source.sha256 {
			return fmt.Errorf("%w: %s digest %s, want %s", errInvalidData, source.name, digest, source.sha256)
		}
		fmt.Fprintf(&generated, "\t%s: []byte(%s),\n", strconv.Quote(source.name), strconv.Quote(string(data)))
	}
	generated.WriteString("}\n")
	formatted, err := format.Source(generated.Bytes())
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}
	if err := os.WriteFile(output, formatted, 0o644); err != nil {
		return fmt.Errorf("write generated source: %w", err)
	}
	return nil
}
