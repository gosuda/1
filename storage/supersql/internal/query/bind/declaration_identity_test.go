func finalizeOwnedDeclaration(t *testing.T, pending *bind.BoundDeclaration, snapshot metadataSnapshot) *bind.BoundDeclaration {
	t.Helper()
	var sequences []*model.Descriptor
	for i, sequence := range pending.PendingSequences() {
		descriptor, err := sequence.Finalize(t.Context(), uint64(700+i))
		if err != nil {
			t.Fatal(err)
		}
		sequences = append(sequences, descriptor)
	}
	bound, err := pending.FinalizeSequences(t.Context(), snapshot, sequences)
	if err != nil {
		t.Fatal(err)
	}
	return bound
}

func TestOwnedSequenceDeclarationsFreezeSerialWithoutIdentity(t *testing.T) {
	snapshot := tableSnapshot(t)
	pending, err := bindTableDeclaration(t, `CREATE TABLE owned (a smallserial PRIMARY KEY, b bigint GENERATED ALWAYS AS IDENTITY (INCREMENT -2 START -5 CACHE 3), c integer GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME custom_sequence))`, snapshot)
	if err != nil {
		t.Fatal(err)
	}
	if len(pending.Descriptors()) != 0 {
		t.Fatal("unfinalized table escaped")
	}
	bound := finalizeOwnedDeclaration(t, pending, snapshot)
	var table *model.Descriptor
	owned := make(map[model.ColumnID]*model.Descriptor)
	for _, descriptor := range bound.Descriptors() {
		if descriptor.Kind() == model.ObjectTable {
			table = descriptor
		}
		if sequence, ok := descriptor.Sequence(); ok {
			owned[sequence.OwnerColumn] = descriptor
		}
	}
	if table == nil || len(owned) != 3 {
		t.Fatalf("table=%v owned=%v", table, owned)
	}
	spec, err := table.Spec(t.Context())
	if err != nil {
		t.Fatal(err)
	}
	serial, always, byDefault := spec.Table.Columns[0], spec.Table.Columns[1], spec.Table.Columns[2]
	if serial.IdentitySequence != 0 || serial.Default == nil || serial.Nullable || serial.Layout.Type.ID != 21 {
		t.Fatalf("serial column=%+v", serial)
	}
	if always.IdentitySequence != owned[2].ID() || !always.IdentityAlways || always.Default != nil || always.Nullable {
		t.Fatalf("always column=%+v", always)
	}
	if byDefault.IdentitySequence != owned[3].ID() || byDefault.IdentityAlways || byDefault.Nullable {
		t.Fatalf("by default column=%+v", byDefault)
	}
	if owned[1].Name().Name != "owned_a_seq" || owned[3].Name().Name != "custom_sequence" {
		t.Fatalf("sequence names=%v %v", owned[1].Name(), owned[3].Name())
	}
	configuration, _ := owned[2].Sequence()
	if configuration.OwnerTable != table.ID() || configuration.Start != -5 || configuration.Increment != -2 || configuration.Cache != 3 {
		t.Fatalf("owned configuration=%+v", configuration)
	}
	snapshot.descriptors = append(snapshot.descriptors, bound.Descriptors()...)
	if _, err := bind.BindColumnDefault(t.Context(), serial.Default, serial.Layout, snapshot, bindingOptions("SELECT 1")); err != nil {
		t.Fatal(err)
	}
	for _, dependency := range bound.Dependencies() {
		for _, descriptor := range bound.Descriptors() {
			if dependency.Object == descriptor.ID() {
				t.Fatal("private dependency escaped into external reads")
			}
		}
	}
}

func TestOwnedSequenceDeclarationRetainsExpressionsAfterCallerMutation(t *testing.T) {
	const sql = `CREATE TABLE owned (id serial, observed bigint DEFAULT nextval('owned_id_seq'), CHECK (currval('owned_id_seq') > 0))`
	parsed, err := zpgparse.Parse(sql)
	if err != nil {
		t.Fatal(err)
	}
	statement := parsed.Stmts[0].Stmt.GetCreateStmt()
	snapshot := tableSnapshot(t)
	options := bind.CreateDeclarationOptions{Bind: bindingOptions(sql), Descriptors: model.DescriptorLimits{MaxBytes: 1 << 20, MaxItems: 100, MaxDepth: 20}, Identities: &declarationIdentities{next: 100}, Owner: (model.Principal{}).OID(), Physical: model.PhysicalIdentity{Generation: 1, EncodingVersion: 1}}
	pending, err := bind.BindCreateTable(t.Context(), statement, snapshot, options)
	if err != nil {
		t.Fatal(err)
	}
	statement.TableElts[1].GetColumnDef().Constraints[0].GetConstraint().RawExpr = nil
	options.Bind.SearchPath[0] = "missing"
	bound := finalizeOwnedDeclaration(t, pending, snapshot)
	spec, err := bound.Descriptors()[0].Spec(t.Context())
	if err != nil {
		t.Fatal(err)
	}
	if spec.Table.Columns[1].Default == nil {
		t.Fatal("caller mutation removed deferred default")
	}
	for _, constraint := range spec.Table.Constraints {
		if constraint.Kind == model.ConstraintCheck && constraint.Expression == nil {
			t.Fatal("CHECK was not compiled")
		}
	}
	snapshot.descriptors = append(snapshot.descriptors, bound.Descriptors()...)
	for _, column := range spec.Table.Columns {
		if column.Default != nil {
			if _, err := bind.BindColumnDefault(t.Context(), column.Default, column.Layout, snapshot, bindingOptions("SELECT 1")); err != nil {
				t.Fatal(err)
			}
		}
	}
}

func TestOwnedSequenceFinalizationRejectsForeignConfigurationWithoutConsumingDraft(t *testing.T) {
	snapshot := tableSnapshot(t)
	pending, err := bindTableDeclaration(t, `CREATE TABLE owned (id serial)`, snapshot)
	if err != nil {
		t.Fatal(err)
	}
	sequence, err := pending.PendingSequences()[0].Finalize(t.Context(), 77)
	if err != nil {
		t.Fatal(err)
	}
	spec, err := sequence.Spec(t.Context())
	if err != nil {
		t.Fatal(err)
	}
	spec.Sequence.Increment = 2
	changed := testDescriptor(t, spec)
	_, err = pending.FinalizeSequences(t.Context(), snapshot, []*model.Descriptor{changed})
	requireCode(t, err, "22023")
	if len(pending.Descriptors()) != 0 {
		t.Fatal("failed finalization exposed table")
	}
	ctx, cancel := context.WithCancel(t.Context())
	cancel()
	_, err = pending.FinalizeSequences(ctx, snapshot, []*model.Descriptor{sequence})
	if !errors.Is(err, context.Canceled) {
		t.Fatalf("canceled finalization=%v", err)
	}
	if _, err := pending.FinalizeSequences(t.Context(), snapshot, []*model.Descriptor{sequence}); err != nil {
		t.Fatal(err)
	}
}

func TestOwnedSequenceDeclarationRejectsConflictingGeneration(t *testing.T) {
	for _, sql := range []string{
		`CREATE TABLE owned (id serial DEFAULT 2)`,
		`CREATE TABLE owned (id serial GENERATED ALWAYS AS IDENTITY)`,
		`CREATE TABLE owned (id integer GENERATED ALWAYS AS IDENTITY DEFAULT 2)`,
		`CREATE TABLE owned (id integer DEFAULT 2 GENERATED BY DEFAULT AS IDENTITY)`,
		`CREATE TABLE owned (id integer GENERATED ALWAYS AS IDENTITY GENERATED BY DEFAULT AS IDENTITY)`,
		`CREATE TABLE owned (id serial NULL)`,
		`CREATE TABLE owned (id integer NULL GENERATED ALWAYS AS IDENTITY)`,
		`CREATE TABLE owned (id integer GENERATED ALWAYS AS IDENTITY (INCREMENT 1 INCREMENT 2))`,
		`CREATE TABLE owned (id integer GENERATED ALWAYS AS IDENTITY (AS bigint))`,
	} {
		t.Run(sql, func(t *testing.T) {
			_, err := bindTableDeclaration(t, sql, tableSnapshot(t))
			requireCode(t, err, "42601")
		})
	}
}
