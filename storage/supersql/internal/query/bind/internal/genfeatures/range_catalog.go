package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
)

func generateRangeCatalog(manifestPath, output string) error {
	if output == "" {
		return nil
	}
	data, err := os.ReadFile(manifestPath)
	if err != nil {
		return err
	}
	var profile manifest
	if err := json.Unmarshal(data, &profile); err != nil {
		return err
	}
	directory := filepath.Join(filepath.Dir(manifestPath), profile.Source["catalog"])
	typeRecords, err := readCatalog(filepath.Join(directory, "pg_type.dat"))
	if err != nil {
		return err
	}
	types := make(map[string]uint32, len(typeRecords))
	kinds := make(map[string]string, len(typeRecords))
	for _, record := range typeRecords {
		id, err := catalogOID(record["oid"])
		if err != nil {
			return err
		}
		types[record["typname"]] = id
		array, err := catalogOID(record["array_type_oid"])
		if err != nil {
			return err
		}
		if array != 0 {
			types["_"+record["typname"]] = array
		}
		kinds[record["typname"]] = record["typtype"]
	}
	classes, err := readOperatorClasses(directory, types)
	if err != nil {
		return err
	}
	functions, err := readCatalog(filepath.Join(directory, "pg_proc.dat"))
	if err != nil {
		return err
	}
	ranges, err := readCatalog(filepath.Join(directory, "pg_range.dat"))
	if err != nil {
		return err
	}
	if len(ranges) != 6 {
		return fmt.Errorf("%w: pinned range family count", errInvalidManifest)
	}
	var generated bytes.Buffer
	generated.WriteString("// Code generated by genfeatures from PostgreSQL REL_18_4 catalogs. DO NOT EDIT.\n" + provenance + "package builtin\n\nvar rangeFamilies = [...]RangeFamilyInfo{\n")
	seen := make(map[uint32]bool, 12)
	for _, record := range ranges {
		rangeName, multiName, subtypeName := record["rngtypid"], record["rngmultitypid"], record["rngsubtype"]
		rangeID, multiID, subtypeID := types[rangeName], types[multiName], types[subtypeName]
		missingIdentity := rangeID == 0 || multiID == 0 || subtypeID == 0
		wrongKind := kinds[rangeName] != "r" || kinds[multiName] != "m"
		duplicate := seen[rangeID] || seen[multiID]
		if missingIdentity || wrongKind || duplicate {
			return fmt.Errorf("%w: invalid range family %s", errInvalidManifest, rangeName)
		}
		seen[rangeID], seen[multiID] = true, true
		var classID uint32
		for _, class := range classes {
			if class.method+"/"+class.name == record["rngsubopc"] && class.method == "btree" && class.input == subtypeID {
				classID = class.id
				break
			}
		}
		if classID == 0 {
			return fmt.Errorf("%w: range subtype operator class %s", errInvalidManifest, rangeName)
		}
		collation, err := catalogOID(record["rngcollation"])
		if err != nil {
			return err
		}
		var canonical, difference uint32
		if name := record["rngcanonical"]; name != "" && name != "-" {
			canonical, err = functionFor(functions, name, []string{rangeName}, rangeName)
			if err != nil {
				return err
			}
		}
		if name := record["rngsubdiff"]; name != "" && name != "-" {
			difference, err = functionFor(functions, name, []string{subtypeName, subtypeName}, "float8")
			if err != nil {
				return err
			}
		}
		fmt.Fprintf(&generated, "{Range:%d,Multirange:%d,Subtype:%d,SubtypeClass:%d,Collation:%d,Canonical:%d,Difference:%d},\n", rangeID, multiID, subtypeID, classID, collation, canonical, difference)
	}
	generated.WriteString("}\n")
	formatted, err := format.Source(generated.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(output, formatted, 0644)
}
