package main

import (
	"strings"
	"testing"
)

// cleanNotices is a minimal notices file that satisfies every rule for the
// modules and files used by the table below. The fenced block inside the first
// entry holds heading- and label-like lines that must be ignored.
const cleanNotices = `# Third-party notices

Introductory paragraph.

## Go modules

### example.com/one

Version: v1.0.0
License: MIT
Source: https://example.com/one
Used by: build

` + "```\n### example.com/two\nLicense: BSD-3-Clause\nSource: https://example.com/two\n```" + `

## Vendored sources and data

### vendored data

Paths:
testdata/**
internal/query/builtin/*_generated.go

License: PostgreSQL
Source: https://example.com/postgres
Version: REL_18_4
Used by: tests
Notice: testdata/COPYRIGHT
`

const generatedHeader = `// Code generated by genfeatures from PostgreSQL REL_18_4 catalogs. DO NOT EDIT.
// Source: PostgreSQL REL_18_4 (https://ftp.postgresql.org/pub/source/v18.4/postgresql-18.4.tar.bz2)
// License: PostgreSQL (see testdata/postgres184/COPYRIGHT)

package builtin
`

var (
	cleanModules = []string{"example.com/one"}
	cleanFiles   = []string{
		"internal/query/builtin/catalog_generated.go",
		"testdata/postgres184/sql/select.sql",
	}
	cleanHeaders = map[string]string{
		"internal/query/builtin/catalog_generated.go": generatedHeader,
		"testdata/postgres184/sql/select.sql":         "SELECT 1;\n",
	}
)

func TestCheckCleanPass(t *testing.T) {
	if findings := check(cleanNotices, cleanModules, cleanFiles, cleanHeaders); len(findings) != 0 {
		t.Fatalf("clean tree reported findings: %v", findings)
	}
}

func TestCheckFencedContentIsIgnored(t *testing.T) {
	// The fenced block above claims example.com/two is covered; a module that
	// only appears inside a fence must still be reported as missing.
	findings := check(cleanNotices, []string{"example.com/two"}, nil, nil)
	if len(findings) != 1 || !strings.Contains(findings[0], "module example.com/two has no '### example.com/two' entry") {
		t.Fatalf("fenced entry was honoured: %v", findings)
	}
}

func TestCheckMissingModule(t *testing.T) {
	findings := check(cleanNotices, []string{"example.com/one", "example.com/missing"}, nil, nil)
	if len(findings) != 1 || !strings.Contains(findings[0], "module example.com/missing has no '### example.com/missing' entry") {
		t.Fatalf("missing module not reported: %v", findings)
	}
}

func TestCheckModuleWithoutLicenseOrSource(t *testing.T) {
	notices := strings.Replace(cleanNotices,
		"License: MIT\nSource: https://example.com/one\n",
		"Version: v1.0.0\n", 1)
	findings := check(notices, []string{"example.com/one"}, nil, nil)
	if len(findings) != 2 ||
		!strings.Contains(findings[0], "module example.com/one entry lacks a 'License:' line") ||
		!strings.Contains(findings[1], "module example.com/one entry lacks a 'Source:' line") {
		t.Fatalf("missing License:/Source: not reported: %v", findings)
	}
}

func TestCheckUncoveredFile(t *testing.T) {
	files := append(append([]string{}, cleanFiles...), "internal/other/zzz.go")
	findings := check(cleanNotices, cleanModules, files, cleanHeaders)
	if len(findings) != 1 || !strings.Contains(findings[0], "file internal/other/zzz.go is not covered") {
		t.Fatalf("uncovered file not reported: %v", findings)
	}
}

func TestCheckMissingHeader(t *testing.T) {
	headers := map[string]string{
		"internal/query/builtin/catalog_generated.go": "// Code generated by genfeatures. DO NOT EDIT.\n\npackage builtin\n",
		"testdata/postgres184/sql/select.sql":         "SELECT 1;\n",
	}
	findings := check(cleanNotices, cleanModules, cleanFiles, headers)
	if len(findings) != 2 ||
		!strings.Contains(findings[0], "generated file internal/query/builtin/catalog_generated.go lacks a '// License:' line") ||
		!strings.Contains(findings[1], "generated file internal/query/builtin/catalog_generated.go lacks a '// Source:' line") {
		t.Fatalf("missing generated header not reported: %v", findings)
	}
}

func TestCheckHeaderBeyondFirstEightLines(t *testing.T) {
	header := "// Code generated by x. DO NOT EDIT.\n" + strings.Repeat("// filler\n", 8) +
		"// Source: somewhere\n// License: MIT\n"
	findings := check(cleanNotices, cleanModules,
		[]string{"internal/query/builtin/catalog_generated.go"},
		map[string]string{"internal/query/builtin/catalog_generated.go": header})
	if len(findings) != 2 {
		t.Fatalf("header outside the first 8 lines accepted: %v", findings)
	}
}

func TestCheckHeadersDisabled(t *testing.T) {
	if findings := check(cleanNotices, cleanModules, cleanFiles, nil); len(findings) != 0 {
		t.Fatalf("nil header map must disable rule (c): %v", findings)
	}
}

func TestCheckMissingPathsGlob(t *testing.T) {
	// A vendored entry without Paths lines attributes nothing.
	notices := strings.Replace(cleanNotices,
		"Paths:\ntestdata/**\ninternal/query/builtin/*_generated.go\n\n", "", 1)
	if strings.Contains(notices, "testdata/**") {
		t.Fatal("fixture edit failed")
	}
	findings := check(notices, cleanModules, []string{"testdata/postgres184/sql/select.sql"}, nil)
	if len(findings) != 1 || !strings.Contains(findings[0], "is not covered by any 'Paths:' glob") {
		t.Fatalf("file without a Paths glob not reported: %v", findings)
	}
}

func TestGlobMatch(t *testing.T) {
	cases := []struct {
		pattern string
		path    string
		want    bool
	}{
		{"testdata/**", "testdata/postgres184/sql/select.sql", true},
		{"testdata/**", "testdata/zzz.txt", true},
		{"testdata/**", "testdata", false},
		{"testdata/**", "other/testdata/x", false},
		{"internal/query/builtin/*_generated.go", "internal/query/builtin/catalog_generated.go", true},
		{"internal/query/builtin/*_generated.go", "internal/query/builtin/internal/x_generated.go", false},
		{"internal/zpgparse/**", "internal/zpgparse/NOTICE", true},
		{"internal/zpgparse/**", "internal/zpgparse", false},
		{"internal/query/builtin/snowball/**", "internal/query/builtin/snowball/english/english_stemmer.go", true},
		{"internal/query/builtin/snowball/**", "internal/query/builtin/signatures_generated.go", false},
	}
	for _, testCase := range cases {
		if got := globMatch(testCase.pattern, testCase.path); got != testCase.want {
			t.Errorf("globMatch(%q, %q) = %v, want %v", testCase.pattern, testCase.path, got, testCase.want)
		}
	}
}

func TestBlockPathsStopsAtFieldLabel(t *testing.T) {
	block := noticeBlock{heading: "x", lines: []string{
		"Paths:",
		"testdata/**",
		"internal/zpgparse/**",
		"",
		"License: PostgreSQL",
		"Source: https://example.com",
	}}
	paths := blockPaths(block)
	if len(paths) != 2 || paths[0] != "testdata/**" || paths[1] != "internal/zpgparse/**" {
		t.Fatalf("blockPaths = %v", paths)
	}
}

const (
	noticeWithDigest = "PostgreSQL 18.4\nSource archive sha256=81a81ec695fb0c7901407defaa1d2f7973617154cf27ba74e3a7ab8e64436094\n  url=https://ftp.postgresql.org/pub/source/v18.4/postgresql-18.4.tar.bz2\n"
	revisionMatch    = "REL_18_4\npostgres_version_num=180004\nsha256=81a81ec695fb0c7901407defaa1d2f7973617154cf27ba74e3a7ab8e64436094\n"
	revisionOther    = "REL_18_4\nsha256=9b4f86dd2ac00b914582e9893d1bad1f54bc9be7108fa794318b8184f921ec08\n"
	featuresMatch    = `{"profile":"embedded_pg18","source":{"archive":"https://ftp.postgresql.org/pub/source/v18.4/postgresql-18.4.tar.bz2","sha256":"81a81ec695fb0c7901407defaa1d2f7973617154cf27ba74e3a7ab8e64436094"}}`
	featuresOther    = `{"source":{"sha256":"9b4f86dd2ac00b914582e9893d1bad1f54bc9be7108fa794318b8184f921ec08"}}`
)

func TestCheckHashesCleanPass(t *testing.T) {
	if findings := checkHashes(noticeWithDigest, revisionMatch, featuresMatch); len(findings) != 0 {
		t.Fatalf("matching digests reported: %v", findings)
	}
}

func TestCheckHashesMismatch(t *testing.T) {
	findings := checkHashes(noticeWithDigest, revisionOther, featuresOther)
	if len(findings) != 2 {
		t.Fatalf("expected two mismatches, got %v", findings)
	}
	for _, finding := range findings {
		if !strings.Contains(finding, "PostgreSQL archive digest mismatch") {
			t.Errorf("unexpected finding: %s", finding)
		}
	}
}

func TestCheckHashesMissingNoticeDigest(t *testing.T) {
	findings := checkHashes("PostgreSQL 18.4\n", revisionMatch, featuresMatch)
	if len(findings) != 1 || !strings.Contains(findings[0], "has no 'Source archive sha256=") {
		t.Fatalf("missing notice digest not reported: %v", findings)
	}
}

func TestCheckHashesSkipsAbsentFixtures(t *testing.T) {
	if findings := checkHashes(noticeWithDigest, "", ""); len(findings) != 0 {
		t.Fatalf("absent fixtures must skip rule (d): %v", findings)
	}
}

func TestCheckHashesMalformedRevision(t *testing.T) {
	findings := checkHashes(noticeWithDigest, "REL_18_4\nno digest here\n", "")
	if len(findings) != 1 || !strings.Contains(findings[0], "testdata/postgres184/REVISION has no 'sha256=") {
		t.Fatalf("malformed revision not reported: %v", findings)
	}
}
