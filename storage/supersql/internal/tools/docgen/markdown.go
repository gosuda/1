package main

import (
	"fmt"
	"sort"
	"strings"
)

// generatedHeader opens every generated document. It is the only marker a
// reader needs to know that the file is owned by this tool.
const generatedHeader = "<!-- Code generated by internal/tools/docgen; DO NOT EDIT. -->"

// mdWriter is the deterministic Markdown emitter shared by every renderer.
//
// Determinism rules it enforces: LF line endings only, no timestamps, no
// absolute paths (renderers pass root-relative locations), caller-sorted data
// only, and table cells that cannot change the table shape because "|" and
// newlines are escaped.
type mdWriter struct {
	buf strings.Builder
}

func newMarkdownWriter() *mdWriter {
	w := &mdWriter{}
	w.line("%s", generatedHeader)
	return w
}

func (w *mdWriter) line(format string, args ...any) {
	fmt.Fprintf(&w.buf, format, args...)
	w.buf.WriteByte('\n')
}

func (w *mdWriter) blank() {
	w.buf.WriteByte('\n')
}

// heading writes an ATX heading. level is clamped to the Markdown maximum.
func (w *mdWriter) heading(level int, text string) {
	if level > 6 {
		level = 6
	}
	w.line("%s %s", strings.Repeat("#", level), text)
	w.blank()
}

// paragraph writes one paragraph of pre-formatted text. Multi-line text keeps
// its own line breaks.
func (w *mdWriter) paragraph(text string) {
	w.line("%s", text)
	w.blank()
}

// code writes a fenced block. The fence is longer than any backtick run in the
// body so that generated content can never terminate it early.
func (w *mdWriter) code(language, body string) {
	fence := strings.Repeat("`", max(3, longestBacktickRun(body)+1))
	if language == "" {
		w.line("%s", fence)
	} else {
		w.line("%s%s", fence, language)
	}
	w.line("%s", strings.TrimRight(body, "\n"))
	w.line("%s", fence)
	w.blank()
}

// table writes a GitHub table. Header and rows are escaped per cell; every row
// must have the same width as the header.
func (w *mdWriter) table(header []string, rows [][]string) {
	cells := make([]string, len(header))
	for i, cell := range header {
		cells[i] = escapeCell(cell)
	}
	w.line("| %s |", strings.Join(cells, " | "))
	separators := make([]string, len(header))
	for i := range header {
		separators[i] = "---"
	}
	w.line("| %s |", strings.Join(separators, " | "))
	for _, row := range rows {
		values := make([]string, len(header))
		for i := range header {
			if i < len(row) {
				values[i] = escapeCell(row[i])
			}
		}
		w.line("| %s |", strings.Join(values, " | "))
	}
	w.blank()
}

func (w *mdWriter) bytes() []byte {
	return []byte(w.buf.String())
}

// escapeCell makes one table cell safe: pipes cannot split a cell and newlines
// cannot split a row.
func escapeCell(cell string) string {
	replacer := strings.NewReplacer(
		"\\", "\\\\",
		"|", "\\|",
		"\r\n", " ",
		"\n", " ",
		"\r", " ",
	)
	return replacer.Replace(cell)
}

func longestBacktickRun(body string) int {
	longest, current := 0, 0
	for _, char := range body {
		if char == '`' {
			current++
			if current > longest {
				longest = current
			}
			continue
		}
		current = 0
	}
	return longest
}

// sortedKeys returns the keys of a string-keyed map in ascending order so that
// renderers never iterate a map directly.
func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

// sortedUnique returns the distinct values of items in ascending order.
func sortedUnique(items []string) []string {
	seen := make(map[string]bool, len(items))
	unique := make([]string, 0, len(items))
	for _, item := range items {
		if seen[item] {
			continue
		}
		seen[item] = true
		unique = append(unique, item)
	}
	sort.Strings(unique)
	return unique
}

// plural renders a count with its singular or plural noun.
func plural(count int, singular, plural string) string {
	if count == 1 {
		return fmt.Sprintf("%d %s", count, singular)
	}
	return fmt.Sprintf("%d %s", count, plural)
}
