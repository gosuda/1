package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
)

func main() {
	file, err := parser.ParseFile(token.NewFileSet(), "internal/pgproto/pg_query.pb.go", nil, 0)
	if err != nil {
		log.Fatal(err)
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by internal/cmd/genapi; DO NOT EDIT.\n")
	out.WriteString("// Source: https://github.com/gosuda/pg18_query_go at 10d566809991b10ff1182369705c19743e16c155; upstream https://github.com/pganalyze/libpg_query at bbfab3948719782cc4ce48dbf2485f8ed0519089\n")
	out.WriteString("// License: BSD-3-Clause AND PostgreSQL (see internal/zpgparse/NOTICE)\n\npackage zpgparse\n\nimport pgproto \"github.com/gosuda/supersql-alpha/internal/zpgparse/internal/pgproto\"\n\n")
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, spec := range gen.Specs {
			writeAlias(&out, gen.Tok, spec)
		}
	}
	source, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("types.go", source, 0644); err != nil {
		log.Fatal(err)
	}
}

func writeAlias(out *bytes.Buffer, kind token.Token, spec ast.Spec) {
	switch spec := spec.(type) {
	case *ast.TypeSpec:
		if ast.IsExported(spec.Name.Name) {
			fmt.Fprintf(out, "type %s = pgproto.%s\n", spec.Name, spec.Name)
		}
	case *ast.ValueSpec:
		for _, name := range spec.Names {
			if ast.IsExported(name.Name) {
				fmt.Fprintf(out, "%s %s = pgproto.%s\n", kind, name, name)
			}
		}
	}
}
