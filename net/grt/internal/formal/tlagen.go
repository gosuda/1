package formal

import (
	"bytes"
	"fmt"
)

// GenerateTLA emits the canonical TLA+ specification and TLC configuration
// derived from the verified GRT/1.1 IR.
func GenerateTLA() (tlaSpec string, tlaCfg string, err error) {
	machines, _, err := CompileAndVerifyAll()
	if err != nil {
		return "", "", err
	}
	gates := AllGates()
	invariants := AllInvariants()

	var b bytes.Buffer
	b.WriteString("------------------------------ MODULE GRT11 ------------------------------\n")
	b.WriteString("\\* Code generated by internal/formal/tlagen.go from the GRT/1.1 Canonical IR. DO NOT EDIT.\n")
	b.WriteString("EXTENDS Naturals, FiniteSets\n\n")

	b.WriteString("VARIABLES\n")
	for i, cm := range machines {
		sep := ","
		if i == len(machines)-1 {
			sep = ""
		}
		fmt.Fprintf(&b, "    st_%s%s \\* Section %s\n", cm.Spec.Name, sep, cm.Spec.SpecSection)
	}
	b.WriteString("\nvars == <<")
	for i, cm := range machines {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "st_%s", cm.Spec.Name)
	}
	b.WriteString(">>\n\n")

	// Emit state domains and predicate sets for each machine.
	for _, cm := range machines {
		m := cm.Spec
		fmt.Fprintf(&b, "\\* --- %s (Section %s) ---\n", m.Name, m.SpecSection)
		fmt.Fprintf(&b, "%sStates == {0..%d}\n", m.Name, len(m.States)-1)
		fmt.Fprintf(&b, "%sEvents == {0..%d}\n", m.Name, len(m.Events)-1)
		for _, p := range m.Predicates {
			writeTLAPredicateSet(&b, m, p.Name, cm.PredicateMasks[p.Name])
		}

		// Emit total transition function.
		fmt.Fprintf(&b, "%sStep(s, ev) ==\n", m.Name)
		b.WriteString("    CASE ")
		firstCase := true
		for _, tr := range m.Transitions {
			if !firstCase {
				b.WriteString("      [] ")
			}
			fmt.Fprintf(&b, "(s = %d /\\ ev = %d) -> %d \\* %s + %s -> %s (%s)\n",
				tr.From, tr.Event, tr.To,
				m.States[tr.From].Name, m.Events[tr.Event].Name, m.States[tr.To].Name, tr.SpecRef)
			firstCase = false
		}
		b.WriteString("      [] OTHER -> s\n\n")
	}

	// Emit conjunctive boolean gate operators.
	b.WriteString("\\* --- Conjunctive Hotpath Gates (Section 22.3) ---\n")
	for _, g := range gates {
		var fullMask uint16
		for _, t := range g.Terms {
			fullMask |= t.Bit
		}
		fmt.Fprintf(&b, "%sRequiredMask == %d\n", g.Name, fullMask)
		fmt.Fprintf(&b, "%sAllow(flags) == flags = %sRequiredMask\n\n", g.Name, g.Name)
	}

	// Emit Init and Next.
	b.WriteString("Init ==\n")
	for i, cm := range machines {
		conj := "/\\"
		if i == 0 {
			conj = "/\\"
		}
		fmt.Fprintf(&b, "    %s st_%s = %d \\* %s\n",
			conj, cm.Spec.Name, cm.Spec.Initial, cm.Spec.States[cm.Spec.Initial].Name)
	}
	b.WriteString("\n")

	for _, cm := range machines {
		m := cm.Spec
		fmt.Fprintf(&b, "Step_%s == \\E ev \\in %sEvents :\n", m.Name, m.Name)
		fmt.Fprintf(&b, "    /\\ st_%s' = %sStep(st_%s, ev)\n", m.Name, m.Name, m.Name)
		b.WriteString("    /\\ UNCHANGED <<")
		firstOther := true
		for _, other := range machines {
			if other.Spec.Name == m.Name {
				continue
			}
			if !firstOther {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "st_%s", other.Spec.Name)
			firstOther = false
		}
		b.WriteString(">>\n\n")
	}

	b.WriteString("Next ==\n")
	for i, cm := range machines {
		disj := "\\/"
		if i == 0 {
			disj = "\\/"
		}
		fmt.Fprintf(&b, "    %s Step_%s\n", disj, cm.Spec.Name)
	}
	b.WriteString("\n")

	// TypeOK and normative safety invariants.
	b.WriteString("TypeOK ==\n")
	for _, cm := range machines {
		fmt.Fprintf(&b, "    /\\ st_%s \\in %sStates\n", cm.Spec.Name, cm.Spec.Name)
	}
	b.WriteString("\n")

	b.WriteString("TerminalAbsorptionOK ==\n")
	for _, cm := range machines {
		m := cm.Spec
		for _, st := range m.States {
			if !st.Terminal {
				continue
			}
			fmt.Fprintf(&b, "    /\\ \\A ev \\in %sEvents : %sStep(%d, ev) = %d \\* %s.%s\n",
				m.Name, m.Name, st.ID, st.ID, m.Name, st.Name)
		}
	}
	b.WriteString("\n")

	b.WriteString("QuietTerminalNoClose ==\n")
	b.WriteString("    \\A s \\in (ConnLifecycle_Terminating \\cup ConnLifecycle_Terminal) :\n")
	b.WriteString("        ConnLifecycleStep(s, 9) = s \\* EV_LOCAL_CLOSE cannot re-enter CLOSING from terminal/terminating\n\n")

	b.WriteString("CipherImmutabilityOK ==\n")
	b.WriteString("    \\A s \\in CipherSelection_Locked, ev \\in CipherSelectionEvents :\n")
	b.WriteString("        CipherSelectionStep(s, ev) = s \\* I01: locked cipher never mutates\n\n")

	b.WriteString("LiveKeyedDisjointTerminating ==\n")
	b.WriteString("    /\\ ConnLifecycle_LiveKeyed \\subseteq ConnLifecycle_KeyBearing\n")
	b.WriteString("    /\\ (ConnLifecycle_LiveKeyed \\cap ConnLifecycle_Terminating) = {}\n\n")

	b.WriteString("SentAckVerifiableExact ==\n")
	b.WriteString("    /\\ 0 \\notin SentPacket_AckVerifiable \\* UNISSUED never ACK-verifiable\n")
	b.WriteString("    /\\ 3 \\notin SentPacket_AckVerifiable \\* BURNED never ACK-verifiable\n\n")

	b.WriteString("\\* Normative Invariant Catalog (verified by explicit-state models):\n")
	for _, inv := range invariants {
		fmt.Fprintf(&b, "\\* [%s] (%s, Section %s): %s\n", inv.ID, inv.Category, inv.SpecSection, inv.Summary)
	}
	b.WriteString("\nSafetyInvariants ==\n")
	b.WriteString("    /\\ TypeOK\n")
	b.WriteString("    /\\ TerminalAbsorptionOK\n")
	b.WriteString("    /\\ QuietTerminalNoClose\n")
	b.WriteString("    /\\ CipherImmutabilityOK\n")
	b.WriteString("    /\\ LiveKeyedDisjointTerminating\n")
	b.WriteString("    /\\ SentAckVerifiableExact\n")
	b.WriteString("Spec == Init /\\ [][Next]_vars\n")
	b.WriteString("=============================================================================\n")

	var cfg bytes.Buffer
	cfg.WriteString("\\* TLC Model Configuration for GRT/1.1\n")
	cfg.WriteString("SPECIFICATION Spec\n")
	cfg.WriteString("INVARIANT TypeOK\n")
	cfg.WriteString("INVARIANT TerminalAbsorptionOK\n")
	cfg.WriteString("INVARIANT QuietTerminalNoClose\n")
	cfg.WriteString("INVARIANT CipherImmutabilityOK\n")
	cfg.WriteString("INVARIANT LiveKeyedDisjointTerminating\n")
	cfg.WriteString("INVARIANT SentAckVerifiableExact\n")
	cfg.WriteString("INVARIANT SafetyInvariants\n")

	return b.String(), cfg.String(), nil
}

func writeTLAPredicateSet(b *bytes.Buffer, m MachineSpec, predName string, mask uint16) {
	fmt.Fprintf(b, "%s_%s == {", m.Name, predName)
	first := true
	for s := range m.States {
		if mask&(uint16(1)<<uint(s)) == 0 {
			continue
		}
		if !first {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "%d", s)
		first = false
	}
	b.WriteString("}\n")
}
