package formal

import (
	"bytes"
	"fmt"
	"go/format"
)

// GenerateEngineGo compiles and verifies all GRT/1.1 FSMs and composed models,
// then emits the zero-allocation Go hotpath implementation for package engine.
func GenerateEngineGo() ([]byte, error) {
	machines, _, err := CompileAndVerifyAll()
	if err != nil {
		return nil, fmt.Errorf("formal FSM verification failed: %w", err)
	}
	if _, err := VerifyAllComposedModels(); err != nil {
		return nil, fmt.Errorf("formal composed model verification failed: %w", err)
	}
	gates := AllGates()

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/formal/gogen.go from the GRT/1.1 Canonical IR. DO NOT EDIT.\n\n")
	b.WriteString("package engine\n\n")

	b.WriteString("// fsmStepResult is a 4-byte value record returned by generated O(1) FSM\n")
	b.WriteString("// transition lookups. It never escapes to the heap.\n")
	b.WriteString("type fsmStepResult struct {\n")
	b.WriteString("\tnext    uint8\n")
	b.WriteString("\tdisp    uint8\n")
	b.WriteString("\tactions uint16\n")
	b.WriteString("}\n\n")

	b.WriteString("const (\n")
	b.WriteString("\tfsmDispTransition    uint8 = 0\n")
	b.WriteString("\tfsmDispStay          uint8 = 1\n")
	b.WriteString("\tfsmDispIgnore        uint8 = 2\n")
	b.WriteString("\tfsmDispProtocolError uint8 = 3\n")
	b.WriteString("\tfsmDispInvalidState  uint8 = 4\n")
	b.WriteString(")\n\n")

	b.WriteString("// Machine identifiers passed to fsmViolation.\n")
	b.WriteString("const (\n")
	for i, cm := range machines {
		fmt.Fprintf(&b, "\tfsmMachine%s uint8 = %d\n", cm.Spec.Name, i)
	}
	b.WriteString(")\n\n")
	b.WriteString("var fsmMachineNames = [...]string{\n")
	for _, cm := range machines {
		fmt.Fprintf(&b, "\t%q,\n", cm.Spec.Name)
	}
	b.WriteString("}\n\n")

	for _, cm := range machines {
		emitMachineGo(&b, cm)
	}
	emitEngineConstAssertions(&b, machines)

	for _, g := range gates {
		emitGateGo(&b, g)
	}

	emitHotpathComposites(&b)

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt generated code: %w\n%s", err, b.String())
	}
	return formatted, nil
}

func emitMachineGo(b *bytes.Buffer, cm *CompiledMachine) {
	m := cm.Spec
	numStates := len(m.States)
	numEvents := len(m.Events)

	fmt.Fprintf(b, "// ---------------------------------------------------------------------------\n")
	fmt.Fprintf(b, "// %s FSM (GRT/1.1 Section %s)\n", m.Name, m.SpecSection)
	fmt.Fprintf(b, "// ---------------------------------------------------------------------------\n\n")

	// Event constants
	fmt.Fprintf(b, "const (\n")
	for _, ev := range m.Events {
		fmt.Fprintf(b, "\t%s_%s uint8 = %d\n", m.GoPrefix, ev.Name, ev.ID)
	}
	fmt.Fprintf(b, ")\n\n")

	// Action bit constants
	if len(m.Actions) > 0 {
		fmt.Fprintf(b, "const (\n")
		for _, act := range m.Actions {
			fmt.Fprintf(b, "\t%s_%s uint16 = 0x%04x\n", m.GoPrefix, act.Name, act.Bit)
		}
		fmt.Fprintf(b, ")\n\n")
	}

	// Bitmask predicate constants and O(1) functions
	if len(m.Predicates) > 0 {
		fmt.Fprintf(b, "const (\n")
		for _, p := range m.Predicates {
			mask := cm.PredicateMasks[p.Name]
			fmt.Fprintf(b, "\t%sMask%s uint16 = 0x%04x\n", m.GoPrefix, p.Name, mask)
		}
		fmt.Fprintf(b, ")\n\n")

		for _, p := range m.Predicates {
			fmt.Fprintf(b, "// %s %s\n", p.GoFunc, p.Doc)
			fmt.Fprintf(b, "func %s(s %s) bool {\n", p.GoFunc, m.StateType)
			fmt.Fprintf(b, "\treturn (uint16(1)<<uint(s))&%sMask%s != 0\n", m.GoPrefix, p.Name)
			fmt.Fprintf(b, "}\n\n")
		}
	}

	// ValidNext adjacency bitmask and O(1) transition check
	fmt.Fprintf(b, "var %sValidNext = [%d]uint16{\n", m.GoPrefix, numStates)
	for s, mask := range cm.ValidNextMask {
		fmt.Fprintf(b, "\t%d: 0x%04x, // %s\n", s, mask, m.States[s].Name)
	}
	fmt.Fprintf(b, "}\n\n")

	fmt.Fprintf(b, "// %sCanTransition reports in O(1) whether transitioning from -> to is permitted by the verified %s FSM.\n", m.GoPrefix, m.Name)
	fmt.Fprintf(b, "func %sCanTransition(from, to %s) bool {\n", m.GoPrefix, m.StateType)
	fmt.Fprintf(b, "\treturn uint(from) < %d && (uint16(1)<<uint(to))&%sValidNext[from] != 0\n", numStates, m.GoPrefix)
	fmt.Fprintf(b, "}\n\n")

	fmt.Fprintf(b, "// %sSet assigns *p = to and reports a transition outside the verified %s\n", m.GoPrefix, m.Name)
	fmt.Fprintf(b, "// adjacency to fsmViolation, so engine/IR drift fails tests instead of passing silently.\n")
	fmt.Fprintf(b, "func %sSet(p *%s, to %s) {\n", m.GoPrefix, m.StateType, m.StateType)
	fmt.Fprintf(b, "\tif !%sCanTransition(*p, to) {\n", m.GoPrefix)
	fmt.Fprintf(b, "\t\tfsmViolation(fsmMachine%s, uint8(*p), uint8(to))\n", m.Name)
	fmt.Fprintf(b, "\t}\n")
	fmt.Fprintf(b, "\t*p = to\n")
	fmt.Fprintf(b, "}\n\n")

	// Total [State][Event] transition lookup table
	fmt.Fprintf(b, "var %sTable = [%d][%d]fsmStepResult{\n", m.GoPrefix, numStates, numEvents)
	for s := range numStates {
		fmt.Fprintf(b, "\t%d: { // %s\n", s, m.States[s].Name)
		for e := range numEvents {
			cell := cm.Table[s][e]
			fmt.Fprintf(b, "\t\t%d: {next: %d, disp: %d, actions: 0x%04x},\n",
				e, cell.Next, uint8(cell.Disp), cell.ActionMask)
		}
		fmt.Fprintf(b, "\t},\n")
	}
	fmt.Fprintf(b, "}\n\n")

	fmt.Fprintf(b, "// %sStep evaluates the total transition table for (%s, event) in O(1) with zero allocations.\n", m.GoPrefix, m.StateType)
	fmt.Fprintf(b, "func %sStep(s %s, ev uint8) fsmStepResult {\n", m.GoPrefix, m.StateType)
	fmt.Fprintf(b, "\tif uint(s) >= %d || uint(ev) >= %d {\n", numStates, numEvents)
	fmt.Fprintf(b, "\t\treturn fsmStepResult{next: uint8(s), disp: fsmDispInvalidState}\n")
	fmt.Fprintf(b, "\t}\n")
	fmt.Fprintf(b, "\treturn %sTable[s][ev]\n", m.GoPrefix)
	fmt.Fprintf(b, "}\n\n")
}

// emitEngineConstAssertions pins every IR state ID to its engine constant
// at compile time (stringer idiom): reordering either side breaks the build
// instead of silently corrupting the bitmask predicates.
func emitEngineConstAssertions(b *bytes.Buffer, machines []*CompiledMachine) {
	b.WriteString("func _() {\n")
	b.WriteString("\tvar x [1]struct{}\n")
	for _, cm := range machines {
		for _, st := range cm.Spec.States {
			if st.EngineConst == "" {
				continue
			}
			fmt.Fprintf(b, "\t_ = x[%s-%d]\n", st.EngineConst, st.ID)
		}
	}
	b.WriteString("}\n\n")
}

func emitGateGo(b *bytes.Buffer, g GateSpec) {
	fmt.Fprintf(b, "// ---------------------------------------------------------------------------\n")
	fmt.Fprintf(b, "// %s Conjunctive Gate (GRT/1.1 Section %s)\n", g.Name, g.SpecSection)
	fmt.Fprintf(b, "// ---------------------------------------------------------------------------\n\n")

	var fullMask uint16
	fmt.Fprintf(b, "const (\n")
	for _, t := range g.Terms {
		fullMask |= t.Bit
		fmt.Fprintf(b, "\t%s_%s uint16 = 0x%04x // %s\n", g.Name, t.Name, t.Bit, t.Doc)
	}
	fmt.Fprintf(b, "\t%s uint16 = 0x%04x\n", g.MaskConst, fullMask)
	fmt.Fprintf(b, ")\n\n")

	fmt.Fprintf(b, "// %s %s\n", g.GoFunc, g.Doc)
	fmt.Fprintf(b, "func %s(flags uint16) bool {\n", g.GoFunc)
	fmt.Fprintf(b, "\treturn flags&%s == %s\n", g.MaskConst, g.MaskConst)
	fmt.Fprintf(b, "}\n\n")
}

func emitHotpathComposites(b *bytes.Buffer) {
	b.WriteString("// ---------------------------------------------------------------------------\n")
	b.WriteString("// Composite Zero-Allocation Hotpath Gate Evaluators\n")
	b.WriteString("// ---------------------------------------------------------------------------\n\n")

	b.WriteString("// fsmEvalStreamHalvesDone evaluates the Section 21.1 local-halves-terminal\n")
	b.WriteString("// precondition for slot retirement using generated O(1) bitmask predicates.\n")
	b.WriteString("func fsmEvalStreamHalvesDone(sendNil bool, sendSt sendState, recvNil bool, recvSt recvState, recvStopped bool) bool {\n")
	b.WriteString("\tsendDone := sendNil || fsmSendIsTerminal(sendSt)\n")
	b.WriteString("\trecvDone := recvNil || fsmRecvIsTerminal(recvSt) || recvStopped\n")
	b.WriteString("\treturn sendDone && recvDone\n")
	b.WriteString("}\n\n")

	b.WriteString("// fsmEvalAmpGate evaluates the Section 6.1 / 17.3 3x byte and 3x packet\n")
	b.WriteString("// anti-amplification gate for unvalidated paths.\n")
	b.WriteString("func fsmEvalAmpGate(validated bool, txBytes, outBytes, rxBytes, txPkts, rxPkts, ampFactor uint64) bool {\n")
	b.WriteString("\tif validated {\n")
	b.WriteString("\t\treturn true\n")
	b.WriteString("\t}\n")
	b.WriteString("\tvar flags uint16\n")
	b.WriteString("\tif txBytes+outBytes <= ampFactor*rxBytes {\n")
	b.WriteString("\t\tflags |= AmpSendGate_BytesWithin3x\n")
	b.WriteString("\t}\n")
	b.WriteString("\tif txPkts+1 <= ampFactor*rxPkts {\n")
	b.WriteString("\t\tflags |= AmpSendGate_PktsWithin3x\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn fsmGateAmpSend(flags)\n")
	b.WriteString("}\n")
}
